"""Docker demo entry point: run the 5-stage pipeline over the 10 monthly Source deliveries.

Everything runs locally inside the container (SQLite ER1 -> Parquet Lake -> DuckDB ER2).
No Neon, Vercel, GitHub or cloud account is needed. The Source data is synthetic and
reproducible (fixed seed), generated by pipeline.generate_classroom_source.

Usage (inside the container):
    python docker/run_demo.py                 # 10 months, with the March data-quality demo
    python docker/run_demo.py --months 3      # first 3 months only
    python docker/run_demo.py --no-error-demo # skip the March DQ block demonstration
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import duckdb  # noqa: E402

from pipeline.dq import DQBlocked  # noqa: E402
from pipeline.generate_classroom_source import BATCHES, build  # noqa: E402
from pipeline.orchestrator import STAGES, reset, run_batch  # noqa: E402

MONTH = {b: f"2026-{i + 1:02d}" for i, b in enumerate(BATCHES)}
LINE = "=" * 78


def banner(text: str) -> None:
    print(f"\n{LINE}\n{text}\n{LINE}", flush=True)


def show_result(batch: str, result: dict) -> dict:
    stage_secs = {s: result["metrics"][s]["elapsed_seconds"] for s in STAGES}
    val = result["metrics"]["validate"]["result"]
    print(f"  stages  : " + " -> ".join(f"{s} {stage_secs[s]:.1f}s" for s in STAGES))
    ing = result["metrics"]["ingest"]["result"]
    dq = ing.get("dq", {})
    print(f"  ingest  : {ing.get('input_records', '?')} source rows | DQ gate: {dq.get('passed', '?')} rules passed, "
          f"{dq.get('failed', '?')} failed, {dq.get('not_checked', '?')} not applicable (table not in this delivery)")
    print(f"  validate: {val['passed']}/{val['checks']} checks passed, "
          f"ER1 net revenue {val['er1_net_revenue']:,.2f} = ER2 net revenue {val['er2_net_revenue']:,.2f}")
    return val


def show_dq_block(error: DQBlocked) -> None:
    report = error.report
    issue = report["issues"][0]
    print("  STOPPED at stage 'ingest' by the data-quality gate (nothing was written to the database).")
    print(f"  rule    : {issue['rule_id']}")
    print(f"  where   : {issue['table']}.{issue['column']} = {issue.get('invalid_value')!r}")
    print("  meaning : an order line refers to a SKU that does not exist in Dim_SKU (invalid reference).")


def kpi_table(er2: Path) -> None:
    with duckdb.connect(str(er2), read_only=True) as db:
        rows = db.execute("""SELECT Year_Month, Gross_Reference_Sales, Net_Revenue, Contribution_Profit,
                                    Profit_Protection_Status
                             FROM View_Shop_Monthly_KPI ORDER BY Year_Month""").fetchall()
        tables = db.execute("SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='main' "
                            "AND table_type='BASE TABLE'").fetchone()[0]
        sales = db.execute("SELECT COUNT(*) FROM Fact_Sales_Order_Item").fetchone()[0]
    print(f"{'month':<9}{'gross':>14}{'net revenue':>14}{'profit':>14}  profit-rule")
    for month, gross, net, profit, status in rows:
        profit_text = f"{float(profit):>14,.2f}" if profit is not None else f"{'n/a':>14}"
        print(f"{month:<9}{float(gross):>14,.2f}{float(net):>14,.2f}{profit_text}  {status}")
    print(f"\nWarehouse (ER2): {tables} tables + 1 view, {sales:,} sales rows in Fact_Sales_Order_Item")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--months", type=int, default=10, help="how many monthly deliveries to run (1-10)")
    parser.add_argument("--no-error-demo", action="store_true", help="skip the March data-quality block demo")
    parser.add_argument("--workspace", default=str(ROOT / "output" / "docker_demo"))
    args = parser.parse_args()
    months = max(1, min(10, args.months))
    workspace, source = Path(args.workspace), ROOT / "output" / "docker_demo_source"

    banner("TikTok Shop Fashion Intelligence - end-to-end pipeline demo (synthetic data, not real TikTok data)")
    print("Generating the reproducible Source deliveries (10 monthly packages x 21 CSV tables)...", flush=True)
    build(source)
    reset(workspace)

    started = time.perf_counter()
    for number, batch in enumerate(BATCHES[:months], start=1):
        banner(f"Month {number}/{months}: {MONTH[batch]}  (delivery '{batch}')")
        if batch == "incremental_02" and not args.no_error_demo:
            print("  First attempt uses the delivery that contains one invalid SKU (data-quality demo):")
            try:
                run_batch(workspace, "incremental_02_error", source)
                print("  UNEXPECTED: the invalid delivery was accepted.")
                return 1
            except DQBlocked as blocked:
                show_dq_block(blocked)
            print("\n  After the Source is corrected, the proper delivery runs:")
        result = run_batch(workspace, batch, source)
        if result["status"] != "SUCCESS" or result["functional_fails"]:
            print(f"  FAILED: {result['status']}")
            return 1
        show_result(batch, result)

    banner("Result: monthly KPIs from the Warehouse")
    kpi_table(workspace / "er2.duckdb")
    print(f"\nTotal time: {time.perf_counter() - started:.1f}s. Files are in: {workspace}")
    print("  er1.sqlite (database) | lake/ (raw + standardized Parquet) | er2.duckdb (warehouse) | reports/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
