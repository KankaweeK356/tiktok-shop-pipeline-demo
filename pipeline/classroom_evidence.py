"""Evidence index for classroom pipeline runs; no fabricated table rows or counts.

Reads the actual SQLite, Parquet and DuckDB generated by pipeline.ci_smoke.
This does not connect to Neon. Neon integration must be verified separately.
"""
from __future__ import annotations

import json
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

import duckdb
import pandas as pd

from .schema import ROOT, parse_dbml

MAX_ROWS = 5
MAX_COLUMNS = 32


def _plain(value):
    if value is None:
        return None
    if hasattr(value, "isoformat"):
        return value.isoformat()
    if hasattr(value, "item"):
        return value.item()
    if isinstance(value, bytes):
        return "<binary>"
    if pd.isna(value):
        return None
    return value


def _preview(frame):
    frame = frame.iloc[:MAX_ROWS, :MAX_COLUMNS]
    return [
        {str(col): _plain(value) for col, value in record.items()}
        for record in frame.to_dict(orient="records")
    ]


def export_classroom_evidence(workspace: Path, destination: Path) -> dict:
    workspace = Path(workspace).resolve()
    destination = Path(destination)
    source_db = workspace / "er1.sqlite"
    warehouse_db = workspace / "er2.duckdb"
    if not source_db.is_file() or not warehouse_db.is_file():
        raise FileNotFoundError("Real ER1 and ER2 run outputs required")

    source_tables, _ = parse_dbml(ROOT / "schemas" / "ER1_V3.dbml")
    warehouse_tables, _ = parse_dbml(ROOT / "schemas" / "ER2_V5.dbml")
    layers = {"source": [], "landing": [], "raw": [], "standardized": [],
              "warehouse": [], "governance": [], "control": []}

    connection = sqlite3.connect(f"file:{source_db}?mode=ro", uri=True)
    try:
        for table in source_tables:
            name = table.name
            safe_name = '"' + name.replace('"', '""') + '"'
            frame = pd.read_sql_query(f"SELECT * FROM {safe_name} LIMIT {MAX_ROWS}", connection)
            count = connection.execute(f"SELECT COUNT(*) FROM {safe_name}").fetchone()[0]
            layers["source"].append({
                "name": name, "type": "sqlite_table", "records": count,
                "columns": [c.name for c in table.columns],
                "preview": _preview(frame),
            })
    finally:
        connection.close()

    lake = workspace / "lake"
    for batch in ("initial", "incremental"):
        for group, ext in (("landing", "*.csv"), ("raw", "*.parquet"),
                           ("standardized", "*.parquet")):
            folder = lake / group / batch
            for path in sorted(folder.glob(ext)):
                if group == "landing":
                    sample = pd.read_csv(path, nrows=MAX_ROWS)
                    # csv row counts are measured, not inferred from preview
                    with path.open(encoding="utf-8-sig") as handle:
                        count = max(0, sum(1 for _ in handle) - 1)
                else:
                    import pyarrow.parquet as parquet
                    p = parquet.ParquetFile(path)
                    count = p.metadata.num_rows
                    sample = p.iter_batches(batch_size=MAX_ROWS).__next__().to_pandas() if count else pd.DataFrame(columns=p.schema_arrow.names)
                layers[group].append({
                    "name": path.name, "batch": batch, "type": group+"_file",
                    "records": count,
                    "columns": list(sample.columns),
                    "preview": _preview(sample),
                    "path": str(path.relative_to(workspace)),
                })
        for group in ("governance", "control"):
            folder = lake / group
            for path in sorted(folder.rglob("*")) if folder.exists() else []:
                if path.is_file() and path.suffix in (".json", ".jsonl", ".csv"):
                    layers[group].append({
                        "name": path.name,
                        "type": "metadata_file",
                        "path": str(path.relative_to(workspace)),
                    })

    conn = duckdb.connect(str(warehouse_db), read_only=True)
    try:
        for table in warehouse_tables:
            name = table.name
            escaped = '"' + name.replace('"', '""') + '"'
            count = conn.execute(f"SELECT COUNT(*) FROM {escaped}").fetchone()[0]
            sample = conn.execute(f"SELECT * FROM {escaped} LIMIT {MAX_ROWS}").df()
            layers["warehouse"].append({
                "name": name, "type": "duckdb_view" if name.startswith("View_") else "duckdb_table",
                "records": count, "columns": list(sample.columns),
                "preview": _preview(sample),
            })
    finally:
        conn.close()

    checks = {}
    for batch in ("initial", "incremental"):
        checkpoint = lake / "control" / f"checkpoint_{batch}.json"
        validation = workspace / "reports" / f"functional_{batch}.json"
        checks[batch] = {
            "checkpoint": json.loads(checkpoint.read_text(encoding="utf-8")) if checkpoint.exists() else None,
            "validation": json.loads(validation.read_text(encoding="utf-8")) if validation.exists() else None,
        }
    errors_file = ROOT / "output" / "test" / "error_suite_summary.json"
    errors = json.loads(errors_file.read_text(encoding="utf-8")) if errors_file.exists() else None
    case_details = []
    for case_dir in sorted((ROOT / "output" / "test").glob("case_*")):
        case_workspace = case_dir / "workspace"
        err_path = case_workspace / "reports" / "error_initial.json"
        events_path = case_workspace / "lake" / "control" / "stage_history.jsonl"
        quarantine = case_workspace / "lake" / "governance" / "quarantine"
        events = []
        if events_path.exists():
            for entry in events_path.read_text(encoding="utf-8").splitlines():
                if entry.strip():
                    events.append(json.loads(entry))
        final_validation = case_workspace / "reports" / "functional_initial.json"
        case_details.append({
            "case_id": case_dir.name.removeprefix("case_"),
            "detected_error": json.loads(err_path.read_text(encoding="utf-8"))
                if err_path.exists() else None,
            "stage_events": events,
            "quarantine_receipts": [
                json.loads(p.read_text(encoding="utf-8"))
                for p in sorted(quarantine.glob("*.json"))
            ] if quarantine.exists() else [],
            "validation_after_retry": json.loads(final_validation.read_text(encoding="utf-8"))
                if final_validation.exists() else None,
        })
    result = {
        "classification": "SYNTHETIC_EDUCATIONAL_NOT_TIKTOK",
        "runner": "github_actions_or_local_python",
        "source_engine": "SQLITE_NOT_NEON",
        "snapshot_at_utc": datetime.now(timezone.utc).isoformat(),
        "layers": layers,
        "stage_evidence": checks,
        "error_recovery_evidence": errors,
        "error_case_details": case_details,
        "neon_connected": False,
        "limitation_th": "ข้อมูลจาก SQLite/PyArrow/DuckDB ที่รันจริง; ยังไม่ได้เชื่อม Neon",
    }
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(result, ensure_ascii=False, indent=2,
                                      default=str), encoding="utf-8")
    return result


if __name__ == "__main__":
    result = export_classroom_evidence(ROOT / "output" / "main",
                                       ROOT / "output" / "classroom_evidence.json")
    print(json.dumps({layer: len(items) for layer, items in result["layers"].items()},
                     ensure_ascii=False, indent=2))
